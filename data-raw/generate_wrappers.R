# Generates R/wrappers.R: one thin pred*From*() function per real (non-
# diagnostic) model in inst/extdata/model_registry.csv. Deliberately NOT
# hand-written -- 52 near-identical functions is exactly the kind of thing
# that drifts out of sync with the registry if maintained by hand. Re-run
# this script (then devtools::document()) whenever model_registry.csv
# changes (new model added/retired, family/link/eps correction, etc.).
#
# Each wrapper is a thin call into rosetta_predict() (R/predict-dispatch.R),
# which does the actual family dispatch -- the wrapper's only job is to (a)
# give the model a RosettaCOTS-style discoverable name and (b) default the
# `eps`/`link`/`size` arguments to the values this exact model was fit with,
# so a caller only ever has to supply `x` (the bundled posterior is used
# unless `post` is given) (and `offset`/`size` for models where that's a genuinely
# data-dependent, representative-effort choice -- see each function's docs).

library(dplyr)

reg <- readr::read_csv("inst/extdata/model_registry.csv", show_col_types = FALSE) |>
  filter(!is_diagnostic)

wrap_text <- function(x, width = 76) paste(strwrap(x, width = width), collapse = "\n#'   ")

model_name_to_wrapper <- function(model_name) {
  parts <- strsplit(model_name, "_")[[1]]
  parts <- parts[nzchar(parts)]
  pascal <- vapply(parts, function(p) paste0(toupper(substr(p, 1, 1)), substr(p, 2, nchar(p))), character(1))
  paste0("pred", paste(pascal, collapse = ""))
}

size_required_msg <- "`size` is required for this model: a representative trial count (e.g. median n_tows backing one row -- see rosetta_models()'s pi_size column)."

gen_one <- function(r) {
  fn <- model_name_to_wrapper(r$model_name)
  title <- sprintf(
    "Predict %s (%s) from %s, %s level",
    r$response_method, r$response_variable, r$predictor_method, gsub("_", "-", r$level)
  )
  details <- sprintf(
    "Response: %s. Predictor: %s. %s",
    r$response_variable, r$predictor_variable, if (!is.na(r$notes)) r$notes else ""
  )

  if (r$family == "beta") {
    body <- paste0(
      "  if (is.null(post)) post <- rosetta_posterior(\"", r$model_name, "\")\n",
      "  predBetaCurve(post, x, n_draws = n_draws)"
    )
    sig <- "function(post = NULL, x, n_draws = 2000)"
    extra_param_doc <- ""
  } else if (r$family == "negbin") {
    body <- sprintf(
      "  if (is.null(post)) post <- rosetta_posterior(\"%s\")\n  predNegBinCurve(post, x, offset = offset, eps = %s, n_draws = n_draws)",
      r$model_name, r$eps
    )
    sig <- "function(post = NULL, x, offset = 0, n_draws = 2000)"
    extra_param_doc <- "#' @param offset Log-effort offset (see Details for which method's effort this model's offset was fit against).\n"
  } else if (r$family == "binomial" && isTRUE(r$has_offset)) {
    body <- sprintf(
      "  if (is.null(post)) post <- rosetta_posterior(\"%s\")\n  predBinomialCurve(post, x, offset = offset, eps = %s, link = \"%s\", size = 1, n_draws = n_draws)",
      r$model_name, r$eps, r$link
    )
    sig <- "function(post = NULL, x, offset = 0, n_draws = 2000)"
    extra_param_doc <- "#' @param offset Log-effort offset (already centered into this model's alpha at fit time -- pass the RAW log(effort) for a new prediction, e.g. `log(tow_distance_m)`; see Details).\n"
  } else { # binomial, no offset, trials()-based
    body <- paste0(
      "  if (is.null(post)) post <- rosetta_posterior(\"", r$model_name, "\")\n",
      "  if (missing(size)) stop(\"", size_required_msg, "\", call. = FALSE)\n",
      sprintf("  predBinomialCurve(post, x, offset = NULL, eps = %s, link = \"%s\", size = size, n_draws = n_draws)", r$eps, r$link)
    )
    sig <- "function(post = NULL, x, size, n_draws = 2000)"
    extra_param_doc <- "#' @param size Representative trial count for this model's prediction interval (see Details / rosetta_models()$pi_size). Required, no default.\n"
  }

  glue::glue(
    "#' {title}\n",
    "#'\n",
    "#' @details\n",
    "#'   {wrap_text(details)}\n",
    "#'\n",
    "#' @param post Posterior-samples matrix for `\"{r$model_name}\"`. Default `NULL` uses the posterior bundled with the package (`rosetta_posterior(\"{r$model_name}\")`).\n",
    "#' @param x Numeric vector of predictor values ({r$predictor_variable}).\n",
    "{extra_param_doc}",
    "#' @param n_draws Number of posterior draws to use. Default 2000.\n",
    "#'\n",
    "#' @return A tibble as described in [predBetaCurve()] / [predNegBinCurve()] / [predBinomialCurve()].\n",
    "#' @export\n",
    "{fn} <- {sig} {{\n",
    "{body}\n",
    "}}\n"
  )
}

header <- c(
  "# Generated by data-raw/generate_wrappers.R -- DO NOT EDIT BY HAND.",
  "# Re-run that script (then devtools::document()) to regenerate after any",
  "# change to inst/extdata/model_registry.csv.",
  "", ""
)

fns <- vapply(seq_len(nrow(reg)), function(i) gen_one(reg[i, ]), character(1))

writeLines(c(header, paste(fns, collapse = "\n")), "R/wrappers.R")
cat("Wrote", nrow(reg), "wrapper functions to R/wrappers.R\n")
