# Generates R/wrappers_d02.R: one thin pass-through wrapper per D-02 model
# in inst/extdata/d02_model_registry.csv, each forwarding (with its exact,
# introspected signature -- not just `...`) to RosettaCOTS's own internal
# per-model function of the same name.
#
# Why pass-through, not reimplemented via RosettaGBR's predBetaCurve()/
# predNegBinCurve()/predBinomialCurve(): D-02's internal functions each do
# bespoke simulation (e.g. predMantaFromCull() injects a lognormal reef
# random effect and sums a per-tow Binomial draw over manta.nTows; see
# model_registry notes), not a uniform marginalized population-level curve.
# Reimplementing that faithfully per model is out of scope here -- this
# script instead re-exports RosettaCOTS's own (unexported) implementation
# under a stable, discoverable RosettaGBR name, with its exact formals
# reproduced so autocomplete/`args()` still work for callers.
#
# RosettaCOTS exports none of these -- only the single COTS_calibrate()
# dispatcher -- so forwarding uses getFromNamespace() (see
# R/d02-helpers.R::rosettacots_fn()), not `RosettaCOTS::`.
#
# Re-run this script (then devtools::document()) whenever
# inst/extdata/d02_model_registry.csv changes, or if a new RosettaCOTS
# version adds/renames/changes the signature of one of these functions.

library(dplyr)

reg <- readr::read_csv("inst/extdata/d02_model_registry.csv", show_col_types = FALSE)

required_pkg <- "RosettaCOTS"
if (!requireNamespace(required_pkg, quietly = TRUE)) {
  stop("RosettaCOTS must be installed to introspect its function signatures and regenerate wrappers_d02.R.")
}
ns <- asNamespace(required_pkg)

wrap_text <- function(x, width = 76) paste(strwrap(x, width = width), collapse = "\n#'   ")

arg_default_str <- function(val) {
  if (identical(val, quote(expr = ))) return(NULL) # no default -- required arg
  if (is.symbol(val)) {
    # RosettaCOTS upstream quirk: 7 functions (predDeepFromTransect,
    # predDeepFromTransom, predMantaCoralFromDeep,
    # predMantaCoralFromTransect, predMantaCoralFromTransom,
    # predTransomFromDeep, predTransomFromTransect) declare a default value
    # of the bare symbol `newDensity`, which is not actually defined
    # anywhere in RosettaCOTS -- calling the function without explicitly
    # supplying that argument errors with "object 'newDensity' not found"
    # (confirmed against the installed RosettaCOTS 1.0.2). Rather than
    # reproduce that broken default (which would also trip an R CMD check
    # "no visible binding for global variable" NOTE), treat it as a
    # required argument here -- functionally identical to upstream's own
    # behaviour, just surfaced at the right call site instead of inside
    # RosettaCOTS's own function body.
    return(NULL)
  }
  deparse(val)
}

gen_one <- function(r) {
  fn <- r$model_name
  if (!exists(fn, envir = ns, inherits = FALSE)) {
    stop("RosettaCOTS no longer has an internal function '", fn, "' -- ",
         "re-check inst/extdata/d02_model_registry.csv against the installed package version.")
  }
  fm <- formals(get(fn, envir = ns))
  arg_names <- names(fm)
  sig_parts <- vapply(arg_names, function(a) {
    d <- arg_default_str(fm[[a]])
    if (is.null(d)) a else paste0(a, " = ", d)
  }, character(1))
  sig <- paste(sig_parts, collapse = ", ")
  call_args <- paste(sprintf("%s = %s", arg_names, arg_names), collapse = ", ")

  title <- sprintf(
    "Predict %s from %s (D-02), via RosettaCOTS",
    r$response_method, r$predictor_method
  )

  glue::glue(
    "#' {title}\n",
    "#'\n",
    "#' @details\n",
    "#'   {wrap_text(r$notes)}\n",
    "#'\n",
    "#'   Response: {r$response_variable}. Predictor: {r$predictor_variable}.\n",
    "#'\n",
    "{roxy_params(arg_names, fm)}",
    "#' @return A data frame, as returned by RosettaCOTS's internal `{fn}()` --\n",
    "#'   see that function's own return-value shape (not RosettaGBR's\n",
    "#'   `predBetaCurve()`/`predNegBinCurve()`/`predBinomialCurve()` tibble\n",
    "#'   contract, since this is a direct pass-through, not a RosettaGBR-native\n",
    "#'   model).\n",
    "#' @export\n",
    "{fn} <- function({sig}) {{\n",
    "  rosettacots_fn(\"{fn}\")({call_args})\n",
    "}}\n"
  )
}

# Minimal per-arg roxygen @param lines -- generic wording since the
# bespoke argument names/meanings live in RosettaCOTS's own help pages
# (?RosettaCOTS::COTS_calibrate and its source), not duplicated here.
roxy_params <- function(arg_names, fm) {
  lines <- vapply(arg_names, function(a) {
    sprintf("#' @param %s See RosettaCOTS's internal documentation / source for this argument's meaning and units.\n", a)
  }, character(1))
  paste(lines, collapse = "")
}

header <- c(
  "# Generated by data-raw/generate_d02_wrappers.R -- DO NOT EDIT BY HAND.",
  "# Re-run that script (then devtools::document()) to regenerate after any",
  "# change to inst/extdata/d02_model_registry.csv or to RosettaCOTS itself.",
  "#",
  "# These are thin pass-throughs to RosettaCOTS's own (unexported) D-02",
  "# per-model prediction functions -- see rosetta_models(source = \"d02\")",
  "# and each function's own @details for provenance. They are NOT built on",
  "# RosettaGBR's predBetaCurve()/predNegBinCurve()/predBinomialCurve() engine.",
  "", ""
)

fns <- vapply(seq_len(nrow(reg)), function(i) gen_one(reg[i, ]), character(1))

writeLines(c(header, paste(fns, collapse = "\n")), "R/wrappers_d02.R")
cat("Wrote", nrow(reg), "D-02 pass-through wrapper functions to R/wrappers_d02.R\n")
